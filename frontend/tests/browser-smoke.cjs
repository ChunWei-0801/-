// Optional functional smoke test against a running isolated development server.
// Install Playwright separately, then run: node frontend/tests/browser-smoke.cjs
const { chromium } = require(process.env.PLAYWRIGHT_MODULE || 'playwright');
const path = require('node:path');
const os = require('node:os');
const frontBase = (process.env.FAMBUDGET_URL || 'http://127.0.0.1:5174').replace(/\/$/, '');
const artifactDir = process.env.FAMBUDGET_ARTIFACT_DIR || os.tmpdir();
const artifact = name => path.join(artifactDir, name);
const origin = new URL(frontBase);
const expectedApi = ['localhost', '127.0.0.1', '[::1]'].includes(origin.hostname) && origin.port === '5174'
  ? origin.protocol + '//' + origin.hostname + ':8000' : origin.origin;
const assert = require('node:assert/strict');
(async () => {
  const browser = await chromium.launch({executablePath: process.env.CHROMIUM_EXECUTABLE || undefined, headless: true, args:['--no-sandbox']});
  const context = await browser.newContext({viewport:{width:1366,height:900}});
  const page = await context.newPage();
  const errors = [];
  page.on('pageerror', e => errors.push(e.message));
  await page.addInitScript(() => localStorage.setItem('fambudget.tour', 'done'));
  await page.goto(frontBase + '/');
  await page.locator('#lpGo').waitFor();
  assert.equal(await page.evaluate(() => API.mode), 'http');
  assert.equal(await page.evaluate(() => API.base), expectedApi);
  await page.waitForTimeout(1500);
  await page.screenshot({path:artifact('fambudget-landing-desktop.png'), fullPage:true});
  await page.goto(frontBase + '/#/register');
  await page.locator('#rgName').fill('發表測試');
  await page.locator('#rgEmail').fill(`frontend.smoke.${Date.now()}@example.test`);
  await page.locator('#rgPw').fill('Local-smoke-9!');
  await page.locator('#regF button[type="submit"]').click();
  await page.locator('[data-su-done="skip"]').waitFor();
  await page.locator('[data-su-done="skip"]').click();
  await page.locator('.first-steps').waitFor();
  await page.locator('.first-steps [data-quick="entry"]').click();
  await page.locator('#paraText').waitFor();
  await page.locator('#paraText').fill('今天薪資30000，早餐55，捷運30，下午喝咖啡');
  await page.locator('#paraGo').click();
  await page.locator('.btbl__r').first().waitFor();
  assert.equal(await page.locator('.btbl__r').count(), 4);
  assert.match(await page.locator('.parse-source').innerText(), /規則解析/);
  assert.equal(await page.locator('#paraSave').isDisabled(), true);
  await page.locator('[data-bi="3"] [data-b="amount"]').fill('0');
  await page.locator('[data-bi="3"] [data-b="amount"]').blur();
  assert.equal(await page.locator('#paraSave').isDisabled(), true);
  await page.locator('[data-bi="3"] [data-b="amount"]').fill('45');
  await page.locator('[data-bi="3"] [data-b="amount"]').blur();
  assert.equal(await page.locator('#paraSave').isDisabled(), false);
  assert.match(await page.locator('#batchStatus').innerText(), /欄位已填齊/);
  await page.waitForTimeout(3500);
  await page.evaluate(()=>window.scrollTo(0,0));
  await page.screenshot({path:artifact('fambudget-parse-desktop.png'), fullPage:true});
  await page.locator('#paraSave').click();
  await page.locator('.btbl__r').first().waitFor({state:'detached'});
  let summary = await page.evaluate(() => API.summary({scope:'me'}));
  assert.equal(summary.income,30000);
  assert.equal(summary.expense,130);
  assert.equal(summary.count,4);
  const tx = await page.evaluate(() => API.transactions({}));
  assert.equal(tx.transactions.length,4);
  assert.equal(tx.transactions.every(t=>t.source==='nlp'),true);
  await page.goto(frontBase + '/#/stats');
  await page.locator('.dt').first().waitFor();
  assert.match(await page.locator('.dt').innerText(), /30,000/);
  assert.match(await page.locator('.dnt').innerText(), /100/);
  await page.screenshot({path:artifact('fambudget-stats-desktop.png'),fullPage:true});
  await page.goto(frontBase + '/#/profile');
  await page.locator('[data-fold="bud"]').click();
  await page.locator('[data-budget]').first().waitFor();
  const foodCat = await page.evaluate(async()=> (await API.categories()).categories.find(c=>/餐|飲食/.test(c.name)&&c.kind==='expense').id);
  const budget = page.locator(`[data-budget="${foodCat}"]`);
  const budgetSave = page.waitForResponse(r=>r.url().includes('/api/budgets')&&r.request().method()==='PUT');
  await budget.fill('1000');
  await budget.blur();
  assert.equal((await budgetSave).status(),200);
  const budgets = await page.evaluate(() => API.budgets({}));
  const food = budgets.budgets.find(b=>b.cat===foodCat);
  assert.equal(food.limit,1000); assert.equal(food.used,100);
  const goal = page.locator('[data-goal]');
  const goalSave = page.waitForResponse(r=>r.url().includes('/api/savings-goal')&&r.request().method()==='PUT');
  await goal.fill('5000'); await goal.blur(); assert.equal((await goalSave).status(),200);
  summary = await page.evaluate(() => API.summary({scope:'me'}));
  assert.equal(summary.savings.goal,5000); assert.equal(summary.net,29870);
  await page.goto(frontBase + '/#/advice');
  await page.locator('#advGen').click();
  await page.locator('#advHint .parse-source').waitFor();
  assert.match(await page.locator('#advHint').innerText(),/未儲存/);
  await page.goto(frontBase + '/#/');
  await page.locator('.bcard').waitFor();
  await page.waitForTimeout(700);
  await page.waitForTimeout(3500);
  await page.evaluate(()=>window.scrollTo(0,0));
  await page.screenshot({path:artifact('fambudget-home-desktop.png'),fullPage:true});
  await page.setViewportSize({width:390,height:844});
  for (const route of ['', 'entry','stats','profile','groups','members','advice']) {
    await page.goto(`${frontBase}/#/${route}`);
    await page.waitForTimeout(500);
    const overflow = await page.evaluate(() => ({width: innerWidth, scroll: document.documentElement.scrollWidth}));
    assert.ok(overflow.scroll <= overflow.width + 1,`horizontal overflow ${route}: ${JSON.stringify(overflow)}`);
  }
  await page.goto(frontBase + '/#/');
  await page.locator('.wal__card').waitFor();
  await page.waitForTimeout(1500);
  await page.evaluate(()=>window.scrollTo(0,0));
  await page.screenshot({path:artifact('fambudget-home-mobile.png'),fullPage:true});
  await page.goto(frontBase + '/?api=#/login');
  assert.equal(await page.evaluate(()=>API.mode),'mock');
  assert.equal(await page.locator('#runtimeNote').isVisible(),true);
  await page.goto(frontBase + '/#/');
  assert.equal(await page.evaluate(()=>API.mode),'http');
  await page.goto(expectedApi + '/#/');
  assert.equal(await page.evaluate(()=>API.base),expectedApi);
  assert.equal(errors.length,0,errors.join('\n'));
  console.log(JSON.stringify({status:'passed',checks:['default real API','registration and onboarding','rule fallback source and correction','NLP confirmed records persisted','income/expense summary','statistics render','budget save and usage','savings goal','advice fallback disclosure','seven mobile routes without overflow','explicit mock and same-origin mode'],summary:{income:summary.income,expense:summary.expense,count:summary.count},browserErrors:errors}));
  await browser.close();
})().catch(e=>{console.error(e.stack);process.exit(1)});
