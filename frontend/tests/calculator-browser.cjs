const assert = require('node:assert/strict');
const path = require('node:path');
const {chromium} = require(process.env.PLAYWRIGHT_MODULE || 'playwright');

(async () => {
  const browser = await chromium.launch({headless:true, executablePath:process.env.CHROMIUM_EXECUTABLE || undefined, args:['--no-sandbox']});
  try {
    const page = await browser.newPage({viewport:{width:390,height:844},hasTouch:true}), errors = [];
    page.on('pageerror', error => errors.push(error.message));
    await page.route('http://calculator.test/**', route => route.fulfill({contentType:'text/html',body:'<!doctype html><meta name="viewport" content="width=device-width,initial-scale=1"><main><a href="#next">Next page</a></main>'}));
    await page.goto('http://calculator.test/');
    await page.addStyleTag({path:path.join(__dirname,'../css/calculator.css')});
    await page.addScriptTag({path:path.join(__dirname,'../js/calculator.js')});
    await page.evaluate(() => FloatingCalculator.configure({enabled:true,userId:'person-a'}));
    await page.getByRole('button',{name:'開啟計算機',exact:true}).click();
    const input = page.getByLabel('計算式',{exact:true});
    await input.fill('sin(30)+2^3'); await input.press('Enter');
    assert.equal(await page.locator('[data-calc-result]').textContent(), '8.5');
    await input.fill('2'); await page.locator('[data-calc-value="(e)"]').click(); await input.press('Enter');
    assert.equal(await input.inputValue(),'2(e)','Euler button inserts a constant rather than a scientific exponent');
    assert.ok(Math.abs(Number(await page.locator('[data-calc-result]').textContent())-2*Math.E)<1e-10);
    await input.fill('sin(30)+2^3'); await input.press('Enter');
    await page.locator('[data-calc-action="mplus"]').click();
    await page.locator('[data-calc-action="clear"]').click();
    await page.locator('[data-calc-action="mr"]').click();
    await input.press('Enter');
    assert.equal(await page.locator('[data-calc-result]').textContent(), '8.5');
    await input.fill('1/0'); await input.press('Enter');
    assert.equal(await page.locator('[data-calc-result]').evaluate(el => el.classList.contains('is-error')), true);
    await page.locator('[data-calc-action="clear"]').click();
    await page.locator('[data-calc-action="mode"]').click();
    await input.fill('sin(pi/2)'); await input.press('Enter');
    assert.equal(await page.locator('[data-calc-result]').textContent(), '1');
    assert.equal(await page.locator('[data-calc-action="mode"]').getAttribute('aria-pressed'), 'true');
    const handle = page.locator('.floating-calculator__handle');
    const box = await handle.boundingBox();
    await page.mouse.move(box.x + 40, box.y + 20); await page.mouse.down();
    await page.mouse.move(box.x + 60, box.y + 30, {steps:4}); await page.mouse.up();
    let panel = await page.locator('.floating-calculator').boundingBox();
    assert.ok(panel.x >= 8 && panel.x + panel.width <= 382.1);
    await handle.focus(); await handle.press('Home'); await handle.press('ArrowRight');
    panel = await page.locator('.floating-calculator').boundingBox();
    assert.equal(panel.x, 16); assert.equal(panel.y, 8);
    const cdp = await page.context().newCDPSession(page);
    const touch = {x:60,y:28};
    await cdp.send('Input.dispatchTouchEvent',{type:'touchStart',touchPoints:[touch]});
    await cdp.send('Input.dispatchTouchEvent',{type:'touchMove',touchPoints:[{x:touch.x+5,y:touch.y+20}]});
    await cdp.send('Input.dispatchTouchEvent',{type:'touchEnd',touchPoints:[]});
    panel = await page.locator('.floating-calculator').boundingBox();
    assert.ok(panel.y > 8, 'Touch moves the panel');
    const saved = {x:panel.x,y:panel.y};
    await input.press('Escape');
    assert.equal(await page.locator('.floating-calculator').isVisible(), false);
    await page.evaluate(() => { location.hash = '#next'; FloatingCalculator.configure({enabled:true,userId:'person-a'}); FloatingCalculator.show(); });
    assert.equal(await input.inputValue(), 'sin(pi/2)', 'Page changes preserve the calculator state');
    await page.evaluate(() => { FloatingCalculator.destroy(); FloatingCalculator.configure({enabled:true,userId:'person-b'}); FloatingCalculator.show(); });
    assert.equal(await input.inputValue(), '', 'A different account gets fresh expression and memory');
    assert.equal(await page.locator('[data-calc-memory]').textContent(), 'M: 0');
    await page.evaluate(() => { FloatingCalculator.configure({enabled:true,userId:'person-a'}); FloatingCalculator.show(); });
    panel = await page.locator('.floating-calculator').boundingBox();
    assert.equal(panel.x,saved.x); assert.equal(panel.y,saved.y);
    await handle.focus(); await handle.press('End');
    await page.setViewportSize({width:320,height:568});
    await page.waitForFunction(() => { const r = document.querySelector('.floating-calculator').getBoundingClientRect(); return r.x >= 8 && r.y >= 8 && r.right <= innerWidth - 7.9 && r.bottom <= innerHeight - 7.9; });
    panel = await page.locator('.floating-calculator').boundingBox();
    assert.ok(panel.x >= 8 && panel.y >= 8 && panel.x + panel.width <= 312.1 && panel.y + panel.height <= 560.1);
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true);
    await page.evaluate(() => FloatingCalculator.configure({enabled:false,userId:'person-a'}));
    assert.equal(await page.locator('.floating-calculator, .floating-calculator-launcher').count(), 0);
    assert.deepEqual(errors, []);
    console.log('PASS: scientific arithmetic, mode and memory; real mouse/touch drag; accessible keyboard movement; per-account positions; route persistence; viewport clamp; settings disable cleanup.');
  } finally { await browser.close(); }
})().catch(error => { console.error(error); process.exitCode = 1; });
